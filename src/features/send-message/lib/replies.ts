const pick = (list: string[]) => list[Math.floor(Math.random() * list.length)]

/** Мок-ответ собеседника */
export const getAutoReply = (text: string) => (text.includes('?') ? pick(ANSWERS_TO_QUESTION) : pick(GENERIC_REPLIES))

